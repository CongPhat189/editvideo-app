"""Quản lý database từ Python models.

    uv run python manage.py make "them bang abc"   # so models với database, sinh file migration
    uv run python manage.py make --empty "policy"  # file migration trống để tự viết SQL (policy, trigger...)
    uv run python manage.py migrate                # áp migration lên database (Supabase)
    uv run python manage.py rollback               # hoàn tác migration gần nhất
    uv run python manage.py status                 # database đang ở phiên bản nào, còn gì chưa áp
    uv run python manage.py check                  # models và database có khớp nhau không
    uv run python manage.py seed                   # nạp dữ liệu mẫu (supabase/seed.sql)
    uv run python manage.py history                # danh sách migration
"""

import argparse
import sys
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

BASE_DIR = Path(__file__).resolve().parent
SEED_FILE = BASE_DIR.parent / "supabase" / "seed.sql"


def alembic_config() -> Config:
    return Config(str(BASE_DIR / "alembic.ini"))


def seed() -> None:
    from sqlalchemy import create_engine

    from app.config import get_settings

    engine = create_engine(get_settings().sqlalchemy_url)
    with engine.begin() as conn:
        conn.connection.dbapi_connection.cursor().execute(SEED_FILE.read_text(encoding="utf-8"))
    engine.dispose()
    print(f"Đã nạp {SEED_FILE.name}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Quản lý database GoClaw Mobile")
    sub = parser.add_subparsers(dest="cmd", required=True)
    make = sub.add_parser("make", help="sinh migration từ thay đổi trong app/models")
    make.add_argument("message", help="mô tả ngắn, vd: 'them bang abc'")
    make.add_argument("--empty", action="store_true", help="không so sánh models, tạo file trống để tự viết SQL")
    sub.add_parser("migrate", help="áp tất cả migration chưa chạy")
    rollback = sub.add_parser("rollback", help="hoàn tác migration")
    rollback.add_argument("steps", nargs="?", type=int, default=1)
    sub.add_parser("status", help="phiên bản hiện tại")
    sub.add_parser("check", help="kiểm tra models khớp database")
    sub.add_parser("seed", help="nạp supabase/seed.sql")
    sub.add_parser("history", help="danh sách migration")
    args = parser.parse_args()

    from app.config import get_settings

    settings = get_settings()
    if not settings.db_password and settings.sqlalchemy_url.host and "supabase" in settings.sqlalchemy_url.host:
        print("Chưa có mật khẩu database: điền DB_PASSWORD trong backend/.env")
        return 1

    cfg = alembic_config()
    if args.cmd == "make":
        cfg.attributes["autogenerate"] = not args.empty
        command.revision(cfg, message=args.message, autogenerate=not args.empty)
    elif args.cmd == "migrate":
        command.upgrade(cfg, "head")
    elif args.cmd == "rollback":
        command.downgrade(cfg, f"-{args.steps}")
    elif args.cmd == "status":
        command.current(cfg, verbose=False)
        command.heads(cfg)
    elif args.cmd == "check":
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as e:
            print(f"KHÔNG KHỚP:\n{e}")
            return 1
        print("Models và database khớp nhau.")
    elif args.cmd == "seed":
        seed()
    elif args.cmd == "history":
        command.history(cfg)
    return 0


if __name__ == "__main__":
    sys.exit(main())
