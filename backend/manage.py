"""Quản lý database từ Python models.

    uv run python manage.py make "them bang abc"   # so models với database, sinh file migration
    uv run python manage.py make --empty "policy"  # file migration trống để tự viết SQL (policy, trigger...)
    uv run python manage.py migrate                # áp migration lên database (Supabase)
    uv run python manage.py rollback               # hoàn tác migration gần nhất
    uv run python manage.py status                 # database đang ở phiên bản nào, còn gì chưa áp
    uv run python manage.py check                  # models và database có khớp nhau không
    uv run python manage.py seed                   # nạp dữ liệu mẫu (supabase/seed.sql)
    uv run python manage.py history                # danh sách migration
    uv run python manage.py agent "Tên" --domain https://goclaw.abc.com --set-key   # tạo/sửa agent, key được mã hóa
    uv run python manage.py set-password 0912345678   # admin đặt lại mật khẩu (app không có Quên mật khẩu)
"""

import argparse
import sys
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

BASE_DIR = Path(__file__).resolve().parent
SEED_FILE = BASE_DIR.parent / "supabase" / "seed.sql"


def alembic_config() -> Config:
    return Config(str(BASE_DIR / "alembic.ini"))


def seed() -> None:
    from sqlalchemy import create_engine

    from app.core.config import get_settings

    engine = create_engine(get_settings().sqlalchemy_url)
    with engine.begin() as conn:
        conn.connection.dbapi_connection.cursor().execute(SEED_FILE.read_text(encoding="utf-8"))
    engine.dispose()
    print(f"Đã nạp {SEED_FILE.name}")


def set_password(phone: str) -> int:
    from getpass import getpass

    from sqlalchemy import create_engine, text

    from app.core.config import get_settings
    from app.core.mobile_security import hash_password
    from app.schemas.mobile import _normalize_phone

    try:
        phone = _normalize_phone(phone)
    except ValueError as e:
        print(e)
        return 1
    password = getpass("Mật khẩu mới: ")
    if not 8 <= len(password) <= 128:
        print("Mật khẩu phải dài 8 đến 128 ký tự")
        return 1
    engine = create_engine(get_settings().sqlalchemy_url, hide_parameters=True)
    with engine.begin() as conn:
        updated = conn.execute(
            text("update public.users set password_hash = :h where phone = :p"),
            {"h": hash_password(password), "p": phone},
        ).rowcount
    engine.dispose()
    print(f"Đã đặt lại mật khẩu cho {phone}, mọi token cũ hết tác dụng" if updated else f"Không có tài khoản {phone}")
    return 0 if updated else 1


def agent(name: str, domain: str | None, set_key: bool, allow_http: bool = False) -> int:
    from getpass import getpass

    from sqlalchemy import create_engine, text

    from app.core.config import get_settings
    from app.core.crypto import encrypt_secret

    # API key gửi trong header: http thường sẽ lộ key, chỉ cho phép khi nói rõ (vd GoClaw trong mạng nội bộ)
    if domain is not None and not domain.startswith("https://") and not (allow_http and domain.startswith("http://")):
        print("--domain phải bắt đầu bằng https:// (mạng nội bộ dùng http thì thêm --allow-http)")
        return 1
    key = None
    if set_key:
        # Nhập qua getpass để key không nằm trong lịch sử lệnh của shell
        plain_key = getpass("API key: ").strip()
        if not plain_key:
            print("API key trống, không lưu gì")
            return 1
        key = encrypt_secret(plain_key)
    engine = create_engine(get_settings().sqlalchemy_url)
    with engine.begin() as conn:
        existing = conn.execute(text("select id from public.agents where name = :n"), {"n": name}).all()
        if len(existing) > 1:
            print(f"Có {len(existing)} agent cùng tên {name!r}, không biết sửa cái nào")
            return 1
        if existing:
            conn.execute(
                text("update public.agents set domain = coalesce(:d, domain), key = coalesce(:k, key) where id = :id"),
                {"d": domain, "k": key, "id": existing[0].id},
            )
        elif domain is None:
            print("Agent mới cần --domain")
            return 1
        else:
            conn.execute(
                text("insert into public.agents (name, domain, key) values (:n, :d, :k)"),
                {"n": name, "d": domain, "k": key},
            )
    engine.dispose()
    print(f"Đã lưu agent {name!r}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Quản lý database GoClaw Mobile")
    sub = parser.add_subparsers(dest="cmd", required=True)
    make = sub.add_parser("make", help="sinh migration từ thay đổi trong app/models.py")
    make.add_argument("message", help="mô tả ngắn, vd: 'them bang abc'")
    make.add_argument("--empty", action="store_true", help="không so sánh models, tạo file trống để tự viết SQL")
    sub.add_parser("migrate", help="áp tất cả migration chưa chạy")
    rollback = sub.add_parser("rollback", help="hoàn tác migration")
    rollback.add_argument("steps", nargs="?", type=int, default=1)
    sub.add_parser("status", help="phiên bản hiện tại")
    sub.add_parser("check", help="kiểm tra models khớp database")
    sub.add_parser("seed", help="nạp supabase/seed.sql")
    sub.add_parser("history", help="danh sách migration")
    agent_cmd = sub.add_parser("agent", help="tạo hoặc sửa agent")
    agent_cmd.add_argument("name")
    agent_cmd.add_argument("--domain")
    agent_cmd.add_argument("--set-key", action="store_true", help="nhập API key (được mã hóa trước khi lưu)")
    agent_cmd.add_argument("--allow-http", action="store_true", help="cho phép domain http:// (mạng nội bộ)")
    password_cmd = sub.add_parser("set-password", help="admin đặt lại mật khẩu cho một số điện thoại")
    password_cmd.add_argument("phone")
    args = parser.parse_args()

    from app.core.config import SupabaseNotConfigured, get_settings

    try:
        settings = get_settings()
        settings.sqlalchemy_url
    except SupabaseNotConfigured as e:
        print(e)
        return 1
    if not settings.db_password and settings.sqlalchemy_url.host and "supabase" in settings.sqlalchemy_url.host:
        print("Chưa có mật khẩu database: điền DB_PASSWORD trong backend/.env")
        return 1

    cfg = alembic_config()
    if args.cmd == "make":
        cfg.attributes["autogenerate"] = not args.empty
        command.revision(cfg, message=args.message, autogenerate=not args.empty)
    elif args.cmd == "migrate":
        command.upgrade(cfg, "head")
    elif args.cmd == "rollback":
        command.downgrade(cfg, f"-{args.steps}")
    elif args.cmd == "status":
        command.current(cfg, verbose=False)
        command.heads(cfg)
    elif args.cmd == "check":
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as e:
            print(f"KHÔNG KHỚP:\n{e}")
            return 1
        print("Models và database khớp nhau.")
    elif args.cmd == "seed":
        seed()
    elif args.cmd == "history":
        command.history(cfg)
    elif args.cmd == "agent":
        return agent(args.name, args.domain, args.set_key, args.allow_http)
    elif args.cmd == "set-password":
        return set_password(args.phone)
    return 0


if __name__ == "__main__":
    sys.exit(main())
